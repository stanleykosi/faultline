import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {generateKeyPairSync,randomBytes,createPrivateKey,createPublicKey} from 'node:crypto';
import {initializeVercelRuntime} from './initialize-vercel-runtime.mjs';
import {HOSTED_OPERATOR_ONLY_INPUTS} from './hosted-private-runtime.mjs';

const encode=value=>Buffer.from(value).toString('base64');
function syntheticEnvironment(){
 const pair=generateKeyPairSync('ed25519');
 return {
  OBJECT_STORE:'supabase',AUTH_DATABASE_SCHEMA:'faultline_identity',
  FAULTLINE_SEALED_SECRET_KEYRING_JSON_B64:encode(JSON.stringify({active:'test-v1',keys:{'test-v1':randomBytes(32).toString('base64')}})),
  FAULTLINE_SEALED_REPORT_SIGNING_PRIVATE_PEM_B64:encode(pair.privateKey.export({format:'pem',type:'pkcs8'})),
  FAULTLINE_SEALED_REPORT_SIGNING_PUBLIC_PEM_B64:encode(pair.publicKey.export({format:'pem',type:'spki'})),
 };
}
async function temporaryParent(t){
 const prefix=path.join(os.tmpdir(),'faultline-vercel-init-test-');
 const parent=await fs.mkdtemp(prefix);
 t.after(async()=>{
  // Remove only the synthetic directory generated by this test, never a supplied path.
  const resolved=await fs.realpath(parent);
  assert.equal(path.dirname(resolved),await fs.realpath(os.tmpdir()));
  assert.ok(path.basename(resolved).startsWith('faultline-vercel-init-test-'));
  await fs.rm(resolved,{recursive:true,force:true});
 });
 return parent;
}

test('materializes valid synthetic keys in a unique private directory and preserves existing files',async t=>{
 const parent=await temporaryParent(t),env=syntheticEnvironment();
 const previous=path.join(parent,'existing-keyring.json');
 await fs.writeFile(previous,'existing synthetic sentinel');env.SECRET_KEYRING_PATH=previous;
 const result=await initializeVercelRuntime({env,parent});
 assert.equal(path.dirname(result.root),parent);
 assert.equal(await fs.readFile(previous,'utf8'),'existing synthetic sentinel');
 assert.notEqual(env.SECRET_KEYRING_PATH,previous);
 const expected={SECRET_KEYRING_PATH:env.FAULTLINE_SEALED_SECRET_KEYRING_JSON_B64,REPORT_SIGNING_KEY_PATH:env.FAULTLINE_SEALED_REPORT_SIGNING_PRIVATE_PEM_B64,REPORT_SIGNING_PUBLIC_KEY_PATH:env.FAULTLINE_SEALED_REPORT_SIGNING_PUBLIC_PEM_B64};
 for(const [name,encoded] of Object.entries(expected)){
  assert.equal(path.dirname(env[name]),result.root);
  assert.deepEqual(await fs.readFile(env[name]),Buffer.from(encoded,'base64'));
  const stat=await fs.lstat(env[name]);assert.ok(stat.isFile());assert.equal(stat.isSymbolicLink(),false);
  if(process.platform!=='win32')assert.equal(stat.mode&0o777,0o600);
 }
 if(process.platform!=='win32')assert.equal((await fs.stat(result.root)).mode&0o777,0o700);
 const signing=createPrivateKey(await fs.readFile(env.REPORT_SIGNING_KEY_PATH));
 assert.deepEqual(createPublicKey(signing).export({type:'spki',format:'der'}),createPublicKey(await fs.readFile(env.REPORT_SIGNING_PUBLIC_KEY_PATH)).export({type:'spki',format:'der'}));
 const again=await initializeVercelRuntime({env,parent});
 assert.notEqual(again.root,result.root);
 assert.deepEqual(await fs.readFile(path.join(result.root,'keyring.json')),Buffer.from(env.FAULTLINE_SEALED_SECRET_KEYRING_JSON_B64,'base64'));
});

test('requires the dedicated hosting profile and all canonical sealed secrets before writing files',async t=>{
 const parent=await temporaryParent(t);
 for(const override of [{OBJECT_STORE:'filesystem'},{AUTH_DATABASE_SCHEMA:'public'},{OBJECT_STORE:undefined}])await assert.rejects(initializeVercelRuntime({env:{...syntheticEnvironment(),...override},parent}),{code:'VERCEL_HOSTING_PROFILE_REQUIRED'});
 for(const name of ['FAULTLINE_SEALED_SECRET_KEYRING_JSON_B64','FAULTLINE_SEALED_REPORT_SIGNING_PRIVATE_PEM_B64','FAULTLINE_SEALED_REPORT_SIGNING_PUBLIC_PEM_B64']){
  for(const invalid of [undefined,'','%%%','YQ','YQ==='])await assert.rejects(initializeVercelRuntime({env:{...syntheticEnvironment(),[name]:invalid},parent}));
 }
 await assert.rejects(initializeVercelRuntime({env:{...syntheticEnvironment(),FAULTLINE_SEALED_SECRET_KEYRING_JSON_B64:encode('x'.repeat(16_385))},parent}));
 assert.deepEqual(await fs.readdir(parent),[]);
});

test('every operator-only secret is rejected before materialization',async t=>{
 const parent=await temporaryParent(t);
 for(const name of HOSTED_OPERATOR_ONLY_INPUTS)await assert.rejects(initializeVercelRuntime({env:{...syntheticEnvironment(),[name]:'synthetic-forbidden-value'},parent}),{code:'VERCEL_OPERATOR_SECRET_FORBIDDEN'});
 assert.deepEqual(await fs.readdir(parent),[]);
});

test('rejects malformed, inactive, noncanonical and oversized keyrings without writing files',async t=>{
 const parent=await temporaryParent(t),key=randomBytes(32).toString('base64');
 const invalid=[null,[],{active:'missing',keys:{v1:key}},{active:'v1',keys:{v1:encode('too short')}},{active:'v1',keys:{v1:key.replace(/=$/,'')}},{active:'v1',keys:Object.fromEntries(Array.from({length:33},(_,i)=>[`v${i}`,key]))},{active:'../escape',keys:{'../escape':key}},{active:'0',keys:[key]},{active:'v1',keys:{v1:key},unexpected:'not part of keyring contract'}];
 for(const value of invalid)await assert.rejects(initializeVercelRuntime({env:{...syntheticEnvironment(),FAULTLINE_SEALED_SECRET_KEYRING_JSON_B64:encode(JSON.stringify(value))},parent}),{code:'VERCEL_KEYRING_INVALID'},`invalid keyring shape ${JSON.stringify(value)}`);
 await assert.rejects(initializeVercelRuntime({env:{...syntheticEnvironment(),FAULTLINE_SEALED_SECRET_KEYRING_JSON_B64:encode('{broken')},parent}),{code:'VERCEL_KEYRING_INVALID'});
 assert.deepEqual(await fs.readdir(parent),[]);
});

test('rejects mismatched signing pairs and non-Ed25519 keys before writing files',async t=>{
 const parent=await temporaryParent(t),first=syntheticEnvironment(),second=syntheticEnvironment();
 await assert.rejects(initializeVercelRuntime({env:{...first,FAULTLINE_SEALED_REPORT_SIGNING_PUBLIC_PEM_B64:second.FAULTLINE_SEALED_REPORT_SIGNING_PUBLIC_PEM_B64},parent}),{code:'VERCEL_SIGNING_KEY_MISMATCH'});
 const ec=generateKeyPairSync('ec',{namedCurve:'prime256v1'});
 await assert.rejects(initializeVercelRuntime({env:{...first,FAULTLINE_SEALED_REPORT_SIGNING_PRIVATE_PEM_B64:encode(ec.privateKey.export({format:'pem',type:'pkcs8'})),FAULTLINE_SEALED_REPORT_SIGNING_PUBLIC_PEM_B64:encode(ec.publicKey.export({format:'pem',type:'spki'}))},parent}),{code:'VERCEL_SIGNING_KEY_MISMATCH'});
 for(const name of ['FAULTLINE_SEALED_REPORT_SIGNING_PRIVATE_PEM_B64','FAULTLINE_SEALED_REPORT_SIGNING_PUBLIC_PEM_B64'])await assert.rejects(initializeVercelRuntime({env:{...first,[name]:encode('invalid synthetic pem')},parent}));
 assert.deepEqual(await fs.readdir(parent),[]);
});
